CREATE TABLE "marcas" (
    id_marca INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL UNIQUE,
    descripcion VARCHAR(500)
);
CREATE TABLE "productos" (
    id_producto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    descripcion VARCHAR(2000),
    precio_original NUMERIC(10,2) NOT NULL,
    descuento NUMERIC(3,2) NOT NULL,
    precio_con_descuento NUMERIC(10,2) GENERATED ALWAYS AS (ROUND(precio_original * (1 - descuento), 2)),
    url_imagen VARCHAR(255),
    id_marca INTEGER NOT NULL REFERENCES "marcas"(id_marca),
    creado_el TIMESTAMP NOT NULL,
    actualizado_el TIMESTAMP NOT NULL
);
